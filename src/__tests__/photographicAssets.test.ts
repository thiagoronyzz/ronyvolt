import { afterEach, describe, expect, it } from 'vitest';
import fs from 'fs';
import path from 'path';
import * as THREE from 'three';
import {
  PHOTO_ASSET_FILES,
  PHOTO_CREDITS,
  applyPhotographicMaps,
  applyPhotographicMapsToScene,
  clonePhoto,
  getPhotographicAssetLibrary,
  getPhotographicAssets,
  photoAssetUrl,
  photographicAssetsEnabled,
  resetPhotographicAssetsForTest,
  setPhotographicAssetsEnabled,
  tagPhotographicMaterial,
} from '../render/PhotographicAssets';

const GENERATED = path.join(process.cwd(), 'public/assets/photos/generated');
const SOURCE = path.join(process.cwd(), 'assets/photos/source');

afterEach(() => {
  resetPhotographicAssetsForTest();
});

describe('photographic asset pipeline', () => {
  it('ships every derived map declared by the loader', () => {
    for (const file of PHOTO_ASSET_FILES) {
      expect(fs.existsSync(path.join(GENERATED, file)), `missing ${file}`).toBe(true);
    }
    const manifest = JSON.parse(fs.readFileSync(path.join(GENERATED, 'manifest.json'), 'utf8')) as {
      files: { name: string }[];
    };
    const declared = new Set<string>(PHOTO_ASSET_FILES as readonly string[]);
    for (const f of manifest.files) expect(declared.has(f.name)).toBe(true);
  });

  it('ships every credited source photograph, thumbnail and the licence file', () => {
    for (const c of PHOTO_CREDITS) {
      expect(fs.existsSync(path.join(SOURCE, c.file)), `missing source ${c.file}`).toBe(true);
      expect(fs.existsSync(path.join(GENERATED, 'thumbs', c.file)), `missing thumb ${c.file}`).toBe(true);
      expect(c.url).toMatch(/^https:\/\//);
    }
    const credits = fs.readFileSync(path.join(process.cwd(), 'assets/photos/CREDITS.md'), 'utf8');
    expect(credits).toContain('ESO/H.H. Heyer');
    expect(credits).toContain('CC BY 4.0');
    expect(credits).toContain('Domínio público');
    expect(credits).toContain('Unsplash License');
    expect(fs.existsSync(path.join(process.cwd(), 'docs/preview/photographic-assets.png'))).toBe(true);
  });

  it('has no unsigned/ambiguous stock or AI imagery in the credited set', () => {
    const all = PHOTO_CREDITS.map((c) => `${c.url} ${c.license}`).join(' ').toLowerCase();
    for (const banned of ['shutterstock', 'adobe', 'getty', 'freepik', 'vecteezy', 'alamy', 'generated by ai']) {
      expect(all).not.toContain(banned);
    }
    expect(PHOTO_CREDITS.filter((c) => c.license.startsWith('CC BY')).length).toBeGreaterThan(0);
  });

  it('falls back to procedural textures when there is no DOM/GPU', () => {
    // Vitest runs in node: `window` is undefined even when a canvas stub exists.
    expect(getPhotographicAssetLibrary()).toBeNull();
    expect(getPhotographicAssets()).toBeNull();
  });

  it('exposes stable absolute URLs for the Vite public directory', () => {
    expect(photoAssetUrl('asphalt_albedo.jpg')).toBe('/assets/photos/generated/asphalt_albedo.jpg');
  });

  it('clones a photo map with its own UV matrix but the same image source', () => {
    const base = new THREE.Texture();
    base.wrapS = THREE.RepeatWrapping;
    base.wrapT = THREE.ClampToEdgeWrapping;
    base.colorSpace = THREE.SRGBColorSpace;
    const a = clonePhoto(base, 2, 6);
    const b = clonePhoto(base, 1, 1, 1);
    expect(a.repeat.x).toBe(2);
    expect(a.repeat.y).toBe(6);
    expect(b.repeat.x).toBe(1);
    expect(b.channel).toBe(1); // aoMap uses uv1
    expect(a.source).toBe(base.source); // no duplicate GPU upload
    expect(a.image).toBe(b.image);
    base.repeat.set(9, 9);
    expect(a.repeat.x).toBe(2); // independent matrix
  });
});

describe('live A/B toggle', () => {
  it('swaps both map sets on a material without rebuilding the scene', () => {
    setPhotographicAssetsEnabled(false);
    expect(photographicAssetsEnabled()).toBe(false);
    const photo = new THREE.Texture();
    const procedural = new THREE.Texture();
    const mat = new THREE.MeshStandardMaterial({ map: procedural, normalMap: procedural });
    tagPhotographicMaterial(mat, { map: photo, normalMap: photo }, { map: procedural, normalMap: procedural });
    expect(mat.map).toBe(procedural);

    const versionBefore = mat.version;
    expect(applyPhotographicMaps(mat, true)).toBe(true);
    expect(mat.map).toBe(photo);
    expect(mat.normalMap).toBe(photo);
    // `needsUpdate` is write-only in three; it bumps `version` to force a
    // program recompile (required when adding/removing an aoMap).
    expect(mat.version).toBeGreaterThan(versionBefore);

    applyPhotographicMaps(mat, false);
    expect(mat.map).toBe(procedural);
    expect(mat.normalMap).toBe(procedural);
  });

  it('walks a scene graph once per shared material', () => {
    const photo = new THREE.Texture();
    const procedural = new THREE.Texture();
    const shared = new THREE.MeshStandardMaterial({ map: procedural });
    tagPhotographicMaterial(shared, { map: photo }, { map: procedural });
    const root = new THREE.Group();
    for (let i = 0; i < 4; i++) root.add(new THREE.Mesh(new THREE.PlaneGeometry(1, 1), shared));
    expect(applyPhotographicMapsToScene(root, true)).toBe(1);
    expect(shared.map).toBe(photo);
    expect(applyPhotographicMapsToScene(root, false)).toBe(1);
    expect(shared.map).toBe(procedural);
  });
});
